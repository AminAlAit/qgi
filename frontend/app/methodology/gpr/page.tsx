/**
 * /methodology/gpr — the public explainer for the QGI Geopolitical Risk layer.
 *
 * Confidence-first (V4.1): the page asserts the validated finding (215-country
 * coverage, movement-tracking accuracy across the 44-country academic
 * benchmark) up top, and keeps the honest corpus-ceiling caveat findable in a
 * dedicated callout — never the headline. No methodology jargon (Spearman,
 * Pearson, gpr_share, FIPS) reaches a heading or stat card; the two metrics are
 * defined in plain English only inside the collapsed "How we measure it" panel.
 * Static RSC: reads data/gpr-country.json at build time, no AWS, no runtime
 * fetch. Tier table is generated by scripts/generate_gpr_country_json.py.
 */

type GprCountry = {
  iso3: string;
  name: string;
  validated: boolean;
  tier: "A" | "B" | "C";
  tier_label: string;
  delta_spearman: number;
  spike_recall: number;
  n_months: number;
  window: string;
  series: { dates: string[]; values: number[] };
};

const META = gpr.meta;
const COUNTRIES = Object.values(gpr.countries) as GprCountry[];

const PCT_TRACKING = Math.round(META.pct_passing_soft_bar * 100);
const PCT_SPIKES = Math.round(META.mean_spike_recall * 100);
const N_OTHER = META.n_total - META.n_validated;

const TIERS: Array<{
  key: "A" | "B" | "C";
  label: string;
  tint: string;
  /** Concrete hex for the sparkline stroke (a CSS var fails in headless/OG
   *  renderers, and a thin muted-text stroke reads too faint). */
  line: string;
  blurb: string;
}> = [
  {
    key: "A",
    label: "Strong signal",
    tint: "#3FBF8F",
    line: "#3FBF8F",
    blurb: "Our movements closely track the published benchmark.",
  },
  {
    key: "B",
    label: "Confirmed signal",
    tint: "var(--qgi-accent)",
    line: "#38bdf8",
    blurb: "Clear, reliable agreement on direction and spikes.",
  },
  {
    key: "C",
    label: "Weak signal",
    tint: "var(--qgi-text-muted)",
    line: "#6B8CAE",
    blurb:
      "Our reading and the benchmark move in the same direction here, but the agreement is weak. We label these indicative rather than confirmed.",
  },
];

