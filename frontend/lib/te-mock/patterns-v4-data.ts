export interface HistoricalExample {
  country: string;
  year: number;
  event_summary: string; // one-line historical fact about the event
}

export interface CurrentMatch {
  country: string;
  match_score: number; // 0..100 shape-similarity rank
  region: string;
}

export interface PatternEntry {
  /** Stable URL-safe id (mirrors recipe_id one-to-one for the mockup). */
  id: string;
  /** Recipe whose canonical movement shape this pattern IS. */
  recipe_id: string;
  /** Display name for the pattern (uses recipe label). */
  name: string;
  /** L1 family identifier (A..H). */
  l1_id: string;
  l1_label: string;
  l1_color: string;
  /** Recipe sub-class label. */
  l2_label: string;
  /** Recipe lifecycle status (drives the chip). */
  status: TrackerRecipe["status"];
  /** Optimal window length in years (from recipe mock). */
  window_y: number;
  /** Number of verified historical positives this shape was derived from. */
  n_positives: number;
  /**
   * 12-point standardized z-score series describing the canonical shape.
   * x-axis: years over the recipe window (downsampled to 12 for the sparkline).
   * y-axis: indicator-composite z-score (negative → benign, positive → danger).
   */
  shape_points: number[];
  /** 5–8 historical country-years where this shape fired. */
  historical_examples: HistoricalExample[];
  /**
   * "curated" — examples drawn from the hand-verified HISTORICAL_EXAMPLES map
   *   above; each is a confirmed historical fact.
   * "illustrative" — generated by fallbackExamples() from the recipe's top-
   *   country mock; NOT a verified-positives corpus; design placeholder only.
   */
  historical_examples_source: "curated" | "illustrative";
  /** Top countries whose CURRENT trajectory best matches the shape. */
  current_top_matches: CurrentMatch[];
  /** Mean match-score across the visible top-10 — surfaced on the gallery card. */
  avg_match_score: number;
}

// ── Shape archetype builders ─────────────────────────────────────────────
// Each archetype is a deterministic 12-point z-score curve. The shape says
// the indicator-composite "story" the recipe rhymes around — gradual ramp,
// step-up, oscillation, collapse, etc. We seed per-recipe variance so each
// pattern has a recognisable signature without ECharts/D3.

const TAU = Math.PI * 2;

function archetypeRamp(intensity = 1, baseline = -1.0): number[] {
  // Classic build-up: indicator composite drifts from benign to crisis.
  return Array.from({ length: 12 }, (_, i) => {
    const t = i / 11;
    return Number((baseline + intensity * 2.2 * Math.pow(t, 1.4)).toFixed(2));
  });
}

function archetypeStep(intensity = 1, stepAt = 5): number[] {
  // Step-function: stable, then rapid escalation, then plateau.
  return Array.from({ length: 12 }, (_, i) => {
    const v = i < stepAt ? -0.8 : 1.4 * intensity;
    const wobble = Math.sin((i / 11) * TAU * 1.5) * 0.15;
    return Number((v + wobble).toFixed(2));
  });
}

function archetypeOscillate(intensity = 1, cycles = 2): number[] {
  // Oscillating shape — boom-bust, electoral cycle, mobilisation peak.
  return Array.from({ length: 12 }, (_, i) => {
    const t = i / 11;
    return Number((Math.sin(t * TAU * cycles) * intensity * 1.2 + t * 0.4).toFixed(2));
  });
}

function archetypeCollapse(intensity = 1): number[] {
  // Inverted ramp — slow benign deterioration tipping to crisis at the end.
  return Array.from({ length: 12 }, (_, i) => {
    const t = i / 11;
    const ramp = -0.3 + 0.4 * t;
    const tail = t > 0.7 ? Math.pow((t - 0.7) / 0.3, 1.8) * 2.0 * intensity : 0;
    return Number((ramp + tail).toFixed(2));
  });
}

function archetypeUShape(intensity = 1): number[] {
  // Recovery / reform shape — crisis peak, then return toward baseline.
  return Array.from({ length: 12 }, (_, i) => {
    const t = i / 11;
    return Number((Math.pow(2 * t - 1, 2) * intensity * 1.6 - 0.6).toFixed(2));
  });
}

