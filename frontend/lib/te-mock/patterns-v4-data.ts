function fallbackExamples(recipe: TrackerRecipe): HistoricalExample[] {
  // Build from the recipe's top-country mock — turn them into illustrative
  // historical-positives for recipes without a curated list above.
  const mock = getMock(recipe);
  const seedYears = [1998, 2004, 2011, 2016, 2020];
  return mock.countriesTop.slice(0, 5).map((c, i) => ({
    country: c.name,
    year: seedYears[i] ?? 2010,
    event_summary: `${recipe.label} event recorded in the QGI catalog (illustrative; see the recipe page for the full event log).`,
  }));
}

function buildCurrentMatches(recipe: TrackerRecipe, baseShape: number[]): CurrentMatch[] {
  // Re-use the top-5 from the recipe mock as the head of the leaderboard;
  // synthesise five more so we have a top-10 per pattern.
  const mock = getMock(recipe);
  const head: CurrentMatch[] = mock.countriesTop.slice(0, 5).map((c) => ({
    country: c.name,
    match_score: Number(Math.min(98, c.score + 12).toFixed(1)),
    region: regionOf(c.name),
  }));
  // Tail — pick plausible runner-ups from a regional pool.
  const POOL = [
    "Sudan",
    "Mali",
    "Niger",
    "Burkina Faso",
    "Ethiopia",
    "Nigeria",
    "Pakistan",
    "Bangladesh",
    "Sri Lanka",
    "Myanmar",
    "Cambodia",
    "Argentina",
    "Venezuela",
    "Honduras",
    "Ecuador",
    "Bolivia",
    "Lebanon",
    "Egypt",
    "Tunisia",
    "Iran",
    "Turkey",
    "Kazakhstan",
    "Uzbekistan",
    "Tajikistan",
    "Belarus",
    "Hungary",
    "Greece",
    "Croatia",
    "Moldova",
    "Serbia",
  ];
  const seen = new Set(head.map((m) => m.country));
  const tail: CurrentMatch[] = [];
  let i = (recipe.recipe_id.charCodeAt(0) + recipe.recipe_id.length) % POOL.length;
  while (tail.length < 5 && i < POOL.length * 3) {
    const c = POOL[i % POOL.length];
    if (!seen.has(c)) {
      const baseScore = Math.max(...baseShape) * 8 + 55;
      const score = Number((baseScore - tail.length * 3.4 - (i % 5) * 0.7).toFixed(1));
      tail.push({
        country: c,
        match_score: Math.max(40, Math.min(85, score)),
        region: regionOf(c),
      });
      seen.add(c);
    }
    i++;
  }
  return [...head, ...tail].sort((a, b) => b.match_score - a.match_score);
}

let _patternsCache: PatternEntry[] | null = null;

/**
 * Build the full patterns catalog — one entry per "populated" recipe
 * (those with curated indicators + window in the recipes.ts mock).
 *
 * "Populated" here = the recipe has a SHAPE_BUILDERS entry. That keeps the
 * gallery to ~25 visible patterns matching the live + queued recipes the
 * tracker considers real candidates, rather than emitting 71 placeholders.
 */
export function getAllPatterns(): PatternEntry[] {
  if (_patternsCache) return _patternsCache;
  const recipes = getAllRecipes();
  const out: PatternEntry[] = [];
  for (const r of recipes) {
    const builder = SHAPE_BUILDERS[r.recipe_id];
    if (!builder) continue; // recipe doesn't ship a curated shape in this mockup
    const mock = getMock(r);
    const shape = builder();
    const curatedExamples = HISTORICAL_EXAMPLES[r.recipe_id];
    const examples = curatedExamples ?? fallbackExamples(r);
    const historical_examples_source: "curated" | "illustrative" = curatedExamples
      ? "curated"
      : "illustrative";
    const currentMatches = buildCurrentMatches(r, shape);
    const avg =
      currentMatches.slice(0, 10).reduce((s, m) => s + m.match_score, 0) /
      Math.min(10, currentMatches.length);
    out.push({
      id: r.recipe_id,
      recipe_id: r.recipe_id,
      name: r.label,
      l1_id: r.l1_id,
      l1_label: r.l1_label,
      l1_color: r.l1_color,
      l2_label: r.l2_label,
      status: r.status,
      window_y: mock.window,
      n_positives: mock.nPositives ?? 0,
      shape_points: shape,
      historical_examples: examples,
      historical_examples_source,
      current_top_matches: currentMatches,
      avg_match_score: Number(avg.toFixed(1)),
    });
  }
  // Stable order: status (graduated → walked → in_progress → legacy → queued)
  // then by avg_match_score desc.
  const STATUS_RANK: Record<TrackerRecipe["status"], number> = {
    graduated: 0,
    walked_no_graduation: 1,
    in_progress: 2,
    live_legacy: 3,
    queued: 4,
  };
  out.sort(
    (a, b) =>
      STATUS_RANK[a.status] - STATUS_RANK[b.status] ||
      b.avg_match_score - a.avg_match_score
  );
  _patternsCache = out;
  return out;
}

export function getPattern(id: string): PatternEntry | undefined {
  return getAllPatterns().find((p) => p.id === id);
}

// ── Ranking entries ─────────────────────────────────────────────────────
// The /patterns/ranking leaderboard — top-30 countries ranked by their
// CURRENT shape-match score against ANY pattern in the catalog. For each
// country we surface the best-matched pattern + the runner-up.

export interface RankingEntry {
  rank: number;
  country: string;
  region: string;
  top_pattern_id: string;
  top_pattern_name: string;
  top_l1_id: string;
  top_l1_color: string;
  top_score: number;
  runner_pattern_id: string;
  runner_pattern_name: string;
  runner_l1_id: string;
  runner_l1_color: string;
  runner_score: number;
}

let _rankingCache: RankingEntry[] | null = null;

/**
 * Build the top-30 country leaderboard. For each country, take its highest
 * shape-match score across every pattern; the runner-up is its second-best
 * pattern. Sort descending. This is the V4 equivalent of the legacy
 * /patterns/ranking page, restated in TE-shape vocabulary.
 */
export function getRanking(): RankingEntry[] {
  if (_rankingCache) return _rankingCache;
  const patterns = getAllPatterns();
  // country → [{ pattern, score }]
  const byCountry = new Map<
    string,
    Array<{ pattern: PatternEntry; score: number; region: string }>
  >();
  for (const p of patterns) {
    for (const m of p.current_top_matches) {
      const list = byCountry.get(m.country) ?? [];
      list.push({ pattern: p, score: m.match_score, region: m.region });
      byCountry.set(m.country, list);
    }
  }
  const rows: RankingEntry[] = [];
  for (const [country, hits] of byCountry.entries()) {
    if (hits.length < 2) continue; // need a runner-up to render the row
    hits.sort((a, b) => b.score - a.score);
    const top = hits[0];
    const runner = hits[1];
    rows.push({
      rank: 0, // filled after sort
      country,
      region: top.region,
      top_pattern_id: top.pattern.id,
      top_pattern_name: top.pattern.name,
      top_l1_id: top.pattern.l1_id,
      top_l1_color: top.pattern.l1_color,
      top_score: Number(top.score.toFixed(1)),
      runner_pattern_id: runner.pattern.id,
      runner_pattern_name: runner.pattern.name,
      runner_l1_id: runner.pattern.l1_id,
      runner_l1_color: runner.pattern.l1_color,
      runner_score: Number(runner.score.toFixed(1)),
    });
  }
  rows.sort((a, b) => b.top_score - a.top_score);
  const top30 = rows.slice(0, 30).map((r, i) => ({ ...r, rank: i + 1 }));
  _rankingCache = top30;
  return top30;
}

/** Distinct L1 families present in the catalog — used by ranking filter chips. */
export function getL1Families(): Array<{ id: string; label: string; color: string }> {
  const seen = new Map<string, { id: string; label: string; color: string }>();
  for (const p of getAllPatterns()) {
    if (!seen.has(p.l1_id)) {
      seen.set(p.l1_id, { id: p.l1_id, label: p.l1_label, color: p.l1_color });
    }
  }
  return Array.from(seen.values()).sort((a, b) => a.id.localeCompare(b.id));
}
